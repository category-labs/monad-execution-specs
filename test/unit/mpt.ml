module Nibbles = Mpt.Nibbles

let gen_nibble : char Gen.t = Gen.(char_range '\x00' '\x0f')
let gen_nibbles : Nibbles.t Gen.t = Gen.(map Nibbles.of_nibble_array (string_of gen_nibble ~nonempty:false))

let round_trip_hp_ok ((nibbles, flag) : Nibbles.t * bool) =
  let hp = Nibbles.hex_prefix_encode nibbles flag in
  let nibbles', flag' = Nibbles.hex_prefix_decode hp in
  Nibbles.(nibbles = nibbles') && flag = flag'

type operation = Add of {key : Bytes.t; value : Bytes.t} | Remove of {key : Bytes.t} | Merkleize
let gen_operation ~gen_key ~gen_value : operation Gen.t =
  Gen.(
    let gen_add =
      let* key = gen_key in
      let* value = gen_value in
      return (Add {key; value})
    in
    let gen_remove =
      let* key = gen_key in
      return (Remove {key})
    in
    let gen_merkleize = return Merkleize in
    frequency [(10, gen_add); (10, gen_remove); (1, gen_merkleize)] )

let print_operation = function
  | Merkleize -> "Merkleize"
  | Add {key; value} ->
      Format.sprintf "Add { key = \"%s\"; value = \"%s\" }" (Bytes.to_hex_string key)
        (Bytes.to_hex_string value)
  | Remove {key} -> Format.sprintf "Remove { key = \"%s\" }" (Bytes.to_hex_string key)

let gen_key =
  Gen.(
    (* Keys are generated by picking one of three possible nibbles, to ensure they overlap. *)
    let gen_nibble_pair = oneofl ['\xaa'; '\xab'; '\xac'; '\xba'; '\xbb'; '\xbc'; '\xca'; '\xcb'; '\xcc'] in
    string_of ~nonempty:true gen_nibble_pair )
let gen_key_set ~size = Gen.(list_size (1 -- size) gen_key)

let gen_run =
  Gen.(
    let* gen_key = oneofl <$> gen_key_set ~size:10 in
    let gen_value = string ~nonempty:true in
    let gen_operation = gen_operation ~gen_key ~gen_value in
    list_size (1 -- 100) gen_operation )

let gen_parallel_runs =
  Gen.(
    (* Small key and value sets ensure enough overlap to make it so that maps are often equal. *)
    let* gen_key = oneofl <$> gen_key_set ~size:2 in
    let gen_value = oneofl ["0"; "1"] in
    let gen_operation = gen_operation ~gen_key ~gen_value in
    list_size (1 -- 100) (Gen.pair gen_operation gen_operation) )

module Mpt_byte_map =
  Mpt.Make
    (struct
      let hash_keys = false
    end)
    (struct
      include Bytes
      let to_bytes = Fun.id
    end)
    (struct
      include Bytes
      let to_bytes = Fun.id
      let commit = Fun.id
    end)

(* TODO: better fuzzing would be ideal. This just checks that MPTs are well-behaved with respect to
   map operations, and that their Merkle roots are consistent. We would also like to compare the Merkle
   roots against a reference version. *)
let rec check_invariants ({data; _} : 'a Mpt.Generic.t) : bool =
  (* Check structural invariants. *)
  match data with
  | Empty -> true
  | Branch (branches, value) ->
      (* Check that there are enough non-empty branches to justify not compressing. *)
      let non_empty =
        (* Non-empty branches plus value if present. *)
        (if Option.is_some value then 1 else 0)
        + ( Iarray.to_seq branches
          |> Seq.filter (function Mpt.Generic.{data = Empty; _} -> false | _ -> true)
          |> Seq.length )
      in
      non_empty > 1 && Iarray.for_all check_invariants branches
  | Extension {ending = Subtree {data = Extension _; _}; _} ->
      (* Should have been compressed to a single Extension. *)
      false
  | Extension {ending = Subtree {data = Empty; _}; _} ->
      (* Should have been compressed to Empty. *)
      false
  | Extension {ending = Subtree st; path} ->
      (* If path was empty, this node should've been replaced by st. *)
      Nibbles.(path <> empty) && check_invariants st
  | Extension {ending = Value _; _} -> true

(* Apply an operation in parallel to all three kinds of maps. *)
let apply_operation (map, mpt_generic, mpt_map) = function
  | Merkleize ->
      let mpt_generic = Mpt.Generic.merkleized ~value_to_bytes:Fun.id mpt_generic in
      let mpt_map = Mpt_byte_map.merkleized mpt_map in
      (map, mpt_generic, mpt_map)
  | Add {key; value} ->
      let map = Bytes.Map.add key value map in
      let mpt_generic = Mpt.Generic.add key value mpt_generic in
      let mpt_map = Mpt_byte_map.add key value mpt_map in
      (map, mpt_generic, mpt_map)
  | Remove {key} ->
      let map = Bytes.Map.remove key map in
      let mpt_generic = Mpt.Generic.remove key mpt_generic in
      let mpt_map = Mpt_byte_map.remove key mpt_map in
      (map, mpt_generic, mpt_map)

(* Generate random insertions/deletions/merkleizations and compare the k/v sets of a regular OCaml map
   against the lazy MPT Mpt.Generic and the MPT-backed map Mpt_byte_map. *)
let check_entries_ok (run : operation list) =
  let map, mpt_generic, mpt_map =
    List.fold_left apply_operation (Bytes.Map.empty, Mpt.Generic.empty, Mpt_byte_map.empty) run
  in
  let check_entries entries = Bytes.Map.equal Bytes.equal map (Bytes.Map.of_seq entries) in
  let same_merkle_root =
    B32.(
      Mpt.Generic.(merkle_root (merkleized ~value_to_bytes:Fun.id mpt_generic))
      = Mpt_byte_map.(merkle_root (merkleized mpt_map)) )
  in
  same_merkle_root
  && check_invariants mpt_generic
  && check_invariants mpt_map.mpt
  && check_entries (Mpt.Generic.to_seq mpt_generic)
  && check_entries (Mpt_byte_map.to_seq mpt_map)

(* Generate two parallel sequences of insertions/deletions and execute them on separate pairs of
   Map/Generic/Mpt_byte_map triples, checking that equality is consistent across implementations. *)
let equal_run_ok (run : (operation * operation) list) =
  let map_1, mpt_generic_1, mpt_map_1 =
    List.fold_left apply_operation (Bytes.Map.empty, Mpt.Generic.empty, Mpt_byte_map.empty) (List.map fst run)
  in
  let map_2, mpt_generic_2, mpt_map_2 =
    List.fold_left apply_operation (Bytes.Map.empty, Mpt.Generic.empty, Mpt_byte_map.empty) (List.map snd run)
  in
  let eq_map = Bytes.Map.equal Bytes.equal map_1 map_2 in
  let eq_generic = Mpt.Generic.equal Bytes.equal mpt_generic_1 mpt_generic_2 in
  let eq_mpt_map = Mpt_byte_map.equal mpt_map_1 mpt_map_2 in
  eq_map = eq_generic && eq_map = eq_mpt_map

let test_case_of_fixture (name, fixture) =
  let open Fixtures.TrieTest in
  let trie =
    List.fold_left
      (fun trie (k, v) -> if Bytes.(v = empty) then Mpt.Generic.remove k trie else Mpt.Generic.add k v trie)
      Mpt.Generic.empty fixture.entries
    |> Mpt.Generic.merkleized ~value_to_bytes:Fun.id
  in
  let root' = Mpt.Generic.merkle_root trie in
  Alcotest.(test_case name `Quick (fun () -> check' b32 ~msg:"Root" ~expected:fixture.root ~actual:root'))

let test_fixture_file ?(hash_keys = false) file =
  let path = "../../third_party/tests/TrieTests/" ^ file in
  let test_fixtures =
    Result.get_ok (Fixtures.TrieTest.of_yojson ~hash_keys (Yojson.Safe.from_file ~fname:file path))
  in
  (file, List.map test_case_of_fixture test_fixtures)

let () =
  let open Alcotest in
  run "Tests on MPT data structures"
    [ ( "Hex-prefix round-trip"
      , [ check_prop
            ~print:Print.(pair Nibbles.to_hex_string bool)
            ~name:"round_trip_hp_ok ns"
            Gen.(pair gen_nibbles bool)
            round_trip_hp_ok ] )
    ; ( "Map entry set fuzzing"
      , [ check_prop ~count:10_000
            ~print:Print.(list print_operation)
            ~name:"check_entries_ok" gen_run check_entries_ok ] )
    ; ( "Map equality laws fuzzing"
      , [ check_prop ~count:10_000
            ~print:Print.(list (pair print_operation print_operation))
            ~name:"equal_run_ok" gen_parallel_runs equal_run_ok ] )
    ; test_fixture_file ~hash_keys:true "hex_encoded_securetrie_test.json"
    ; test_fixture_file ~hash_keys:true "trietest_secureTrie.json"
    ; test_fixture_file ~hash_keys:true "trieanyorder_secureTrie.json"
    ; test_fixture_file "trietest.json"
    ; test_fixture_file "trieanyorder.json" ]
