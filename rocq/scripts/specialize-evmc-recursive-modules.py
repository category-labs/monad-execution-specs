#!/usr/bin/env python3
"""Specialize the generated EVMC recursive-module approximation."""

from __future__ import annotations

import os
import re
import sys
import textwrap
from pathlib import Path


def replace_once(
    source: str, pattern: re.Pattern[str], replacement: str, description: str
) -> str:
    source, count = pattern.subn(lambda _match: replacement, source)
    if count != 1:
        raise SystemExit(
            f"expected one {description} in generated Evmc.v, found {count}"
        )
    return source


def exact(value: str) -> re.Pattern[str]:
    return re.compile(re.escape(value))


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(f"usage: {sys.argv[0]} GENERATED_EVMC_FILE")

    path = Path(sys.argv[1])
    # Only ASCII syntax is rewritten; retain arbitrary generated byte-string
    # payloads exactly, including bytes that are not valid UTF-8.
    with path.open(encoding="latin-1", newline="") as source_file:
        source = source_file.read()

    source = replace_once(
        source,
        re.compile(
            r"\n    _rocq_recursive_module_seed :\n.*?\n  }\.",
            re.MULTILINE | re.DOTALL,
        ),
        "\n  }.",
        "recursive-module seed field",
    )
    source = replace_once(
        source,
        exact("  Arguments Build_FArgs {_} _ _ _ {_}.\n"),
        "  Arguments Build_FArgs {_}.\n",
        "recursive-module Build_FArgs declaration",
    )
    source = replace_once(
        source,
        re.compile(
            r"\n  #\[local\] Instance _rocq_recursive_module_seed_instance.*?"
            r"\n    _rocq_recursive_module_seed\.\n",
            re.MULTILINE | re.DOTALL,
        ),
        "\n",
        "recursive-module seed instance",
    )

    base_definitions = textwrap.dedent(
        """\
        (** [Vm_n] invokes [Host_(n-1)], whose recursive VM call invokes
            [Vm_(n-2)].  Fuel [2 * 1024 + 1] therefore covers every call depth
            admitted by the source VM's [max_stack_depth] check. *)
        Definition recursive_module_fuel : nat := 2049%nat.

        (** This VM is reached only after exhausting the modeled call-depth budget.
            It implements the source VM's depth-failure behavior without requiring an
            arbitrary inhabitant of the mutually recursive module types. *)
        Definition recursive_module_base_vm `{_fargs : FArgs} :
            V.SIG (_fargs := V.Build_FArgs (@T T_t _fargs)) :=
          {|
            V.SIG.execute :=
              fun (_message : Message.t) (_code : string)
                  (state : (@T T_t _fargs).(Vm_H_signature.t)) =>
                ({| Result.t.status_code := Result.StatusCode.Call_depth_exceeded;
                    Result.t.gas_left := (0 : Int64.t);
                    Result.t.gas_refund := (0 : Int64.t);
                    Result.t.output_data := Byte_string.Bytes.empty;
                    Result.t.create_address :=
                      RocqOfOCaml.OCamlString.make_nat 20%nat ("000"%char) |},
                 state)
          |}.

        Definition recursive_module_seed `{_fargs : FArgs} :
            HOST (t := T.(Vm_H_signature.t)) *
            V.SIG (_fargs := V.Build_FArgs T) :=
          (HostF recursive_module_base_vm, recursive_module_base_vm).

        """
    )
    base_definitions = "".join(
        f"  {line}" for line in base_definitions.splitlines(keepends=True)
    )

    knot = "\n  Definition _recursive_modules_Host_Vm `{_fargs : FArgs} :"
    source = replace_once(
        source,
        exact(knot),
        f"\n{base_definitions}{knot[1:]}",
        "recursive-module knot definition",
    )
    source = replace_once(
        source,
        re.compile(
            r"recursive_module_unroll recursive_module_default_fuel"
            r"\n      \(use_unreachable _rocq_recursive_module_seed\)"
        ),
        "recursive_module_unroll recursive_module_fuel recursive_module_seed",
        "generic recursive-module unroll call",
    )
    source = replace_once(
        source,
        re.compile(
            r"\n  `\{_rocq_recursive_module_seed :\n.*?\} :=",
            re.MULTILINE | re.DOTALL,
        ),
        " :=",
        "public recursive-module seed requirement",
    )

    temporary = path.with_name(f"{path.name}.tmp.{os.getpid()}")
    with temporary.open("w", encoding="latin-1", newline="") as target_file:
        target_file.write(source)
    os.replace(temporary, path)


if __name__ == "__main__":
    main()
