#!/bin/sh
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
rocq_root="$repo_root/rocq"
source_root="$repo_root/lib"
translator_root=${ROCQ_OF_OCAML_ROOT:-"$repo_root/.rocq-tools/rocq-of-ocaml"}
switch=${ROCQ_OPAM_SWITCH:-"$repo_root/.opam-rocq-of-ocaml"}
config="$rocq_root/config/translation.json"
cmt_directory="$repo_root/_build/default/lib/.monad_lib.objs/byte"
dependency_directory="$repo_root/_build/default/lib/.monad_lib.objs"
output="$rocq_root/generated/next"
output_hashes="$rocq_root/generated.sha256"
staging="$rocq_root/generated/.next-staging-$$"
metadata="$rocq_root/generated/.assumption-metadata-$$"
metadata_input="$rocq_root/generated/.assumption-input-$$"
keep_metadata=${KEEP_ASSUMPTION_METADATA:-}
manifest="$rocq_root/generated/.translation-manifest-$$"
edges="$rocq_root/generated/.translation-edges-$$"
order="$rocq_root/generated/.translation-order-$$"
inputs_before="$rocq_root/generated/.translation-inputs-before-$$"
inputs_after="$rocq_root/generated/.translation-inputs-after-$$"

if command -v sha256sum >/dev/null 2>&1; then
  hash_command=sha256sum
elif command -v shasum >/dev/null 2>&1; then
  hash_command='shasum -a 256'
else
  printf 'Neither sha256sum nor shasum is available.\n' >&2
  exit 1
fi

cleanup() {
  rm -rf "$staging"
  if [ -z "$keep_metadata" ]; then
    rm -rf "$metadata"
  fi
  rm -rf "$metadata_input"
  rm -f "$manifest" "$edges" "$order" "$inputs_before" "$inputs_after"
}
trap cleanup EXIT HUP INT TERM

capitalize() {
  value=$1
  first=$(printf '%s' "$value" | cut -c 1 | tr '[:lower:]' '[:upper:]')
  rest=$(printf '%s' "$value" | cut -c 2-)
  printf '%s%s' "$first" "$rest"
}

module_path() {
  path=$1
  result=
  old_ifs=$IFS
  IFS=/
  set -- $path
  IFS=$old_ifs
  for component do
    component=$(capitalize "$component")
    if [ -z "$result" ]; then
      result=$component
    else
      result="$result/$component"
    fi
  done
  printf '%s' "$result"
}

source_module_stem() {
  path=$1
  directory=$(dirname "$path")
  base=$(basename "$path")

  # With Dune's [include_subdirs qualified], [foo/foo.ml] implements module
  # [Foo], rather than a nested module [Foo.Foo].
  if [ "$directory" != "." ] && [ "$(basename "$directory")" = "$base" ]; then
    printf '%s' "$directory"
  else
    printf '%s' "$path"
  fi
}

logical_path() {
  printf 'MonadVM.%s' "$(printf '%s' "$1" | tr / .)"
}

compilation_unit() {
  stem=$(source_module_stem "$1")
  printf 'monad_lib__%s' "$(module_path "$stem" | sed 's|/|__|g')"
}

is_excluded_source() {
  case "$1" in
    fixtures.ml) return 0 ;;
    *) return 1 ;;
  esac
}

mkdir -p "$staging" "$metadata" "$metadata_input"

opam exec --switch="$switch" -- \
  dune build --root="$translator_root" src/rocqOfOCaml.exe

# The Merlin helper reads Dune's typed source artifacts. Refresh them before
# translation and reject a run if another build or source edit changes them
# before the generated tree is installed.
opam exec --switch="$switch" -- \
  dune build --pkg=disabled --root="$repo_root" lib/monad_lib.cma

snapshot_inputs() {
  {
    find "$source_root" -type f -name '*.ml'
    find "$dependency_directory" -type f \
      \( -name '*.cmt' -o -name '*.impl.all-deps' \)
  } | LC_ALL=C sort | while IFS= read -r input; do
    $hash_command "$input"
  done
}

snapshot_inputs >"$inputs_before"

# Record source paths and their Dune compilation-unit names.  The latter let
# us use Dune's dependency analysis instead of reanalyzing source-level names,
# which can be shadowed by project modules such as [String].
find "$source_root" -type f -name '*.ml' | LC_ALL=C sort |
while IFS= read -r source; do
  relative=${source#"$source_root"/}
  if is_excluded_source "$relative"; then
    continue
  fi
  source_stem=${relative%.ml}
  unit=$(compilation_unit "$source_stem")
  prefix=$(module_path "$(source_module_stem "$source_stem")" | tr / .)
  printf '%s\t%s\t%s\n' "$unit" "$source" "$prefix"
done >"$manifest"

# [*.impl.all-deps] is generated by Dune from the typed compilation graph.
# Give [tsort] dependency-before-dependent edges, restricting them to source
# units translated by this script.
while IFS="$(printf '\t')" read -r unit source prefix; do
  printf '%s %s\n' "$unit" "$unit"
  dependency_file="$dependency_directory/$unit.impl.all-deps"
  if [ -f "$dependency_file" ]; then
    while IFS= read -r dependency; do
      if cut -f 1 "$manifest" | grep -Fqx "$dependency"; then
        printf '%s %s\n' "$dependency" "$unit"
      fi
    done <"$dependency_file"
  fi
done <"$manifest" >"$edges"

tsort "$edges" >"$order"

while IFS= read -r unit; do
  entry=$(rg -m 1 "^${unit}$(printf '\t')" "$manifest" || true)
  if [ -z "$entry" ]; then
    printf 'No source manifest entry for compilation unit %s\n' "$unit" >&2
    exit 1
  fi
  source=$(printf '%s\n' "$entry" | cut -f 2)
  prefix=$(printf '%s\n' "$entry" | cut -f 3)
  relative=${source#"$source_root"/}
  source_stem=${relative%.ml}
  target="$staging/$(module_path "$(source_module_stem "$source_stem")").v"
  dependency_file="$dependency_directory/$unit.impl.all-deps"
  mkdir -p "$(dirname "$target")"

  # Only import assumption specifications from this unit's OCaml
  # dependencies. Unrelated modules can expose identically shaped functors;
  # their specifications must not be substituted into this unit's types.
  rm -f "$metadata_input"/*.rocq-assumptions
  if [ -f "$dependency_file" ]; then
    while IFS= read -r dependency; do
      sidecar="$metadata/$dependency.rocq-assumptions"
      if [ -f "$sidecar" ]; then
        ln -s "$sidecar" "$metadata_input/$dependency.rocq-assumptions"
      fi
    done <"$dependency_file"
  fi

  printf 'Translating %s\n' "$relative"
  # The translator's Merlin helper runs dune from its nested checkout; point
  # that child process at the source tree containing these compilation units.
  DUNE_ROOT="$repo_root" opam exec --switch="$switch" -- \
    "$translator_root/_build/default/src/rocqOfOCaml.exe" \
    -config "$config" \
    -project-cmt-dir "$cmt_directory" \
    -assumption-metadata-dir "$metadata_input" \
    -assumption-metadata-output \
      "$metadata/$unit.rocq-assumptions" \
    -assumption-prefix "$(logical_path "$prefix")" \
    -output "$target" \
    "$source"

  python3 "$rocq_root/scripts/expand-qualified-requires.py" \
    "$target" "$manifest" "$dependency_file" "$(logical_path "$prefix")"

  if [ "$relative" = "evmc.ml" ]; then
    python3 "$rocq_root/scripts/specialize-evmc-recursive-modules.py" "$target"
  fi
done <"$order"

# Dune's qualified subdirectories create OCaml namespace compilation units
# without corresponding source files.  Generate the equivalent Rocq modules.
find "$source_root" -mindepth 1 -type d | LC_ALL=C sort -r |
while IFS= read -r source_directory; do
  relative=${source_directory#"$source_root"/}
  namespace=$(module_path "$relative")
  target="$staging/$namespace.v"
  logical_namespace=$(logical_path "$namespace")
  mkdir -p "$(dirname "$target")"

  # A same-named source such as [precompiles/precompiles.ml] implements the
  # directory module itself, and its translation already occupies [target].
  if [ -f "$target" ]; then
    continue
  fi

  {
    printf '(** File generated by scripts/generate-rocq.sh. *)\n'

    find "$source_directory" -mindepth 1 -maxdepth 1 -type f -name '*.ml' |
      LC_ALL=C sort |
      while IFS= read -r child_source; do
        child_relative=${child_source#"$source_root"/}
        if is_excluded_source "$child_relative"; then
          continue
        fi
        child=$(capitalize "$(basename "$child_source" .ml)")
        printf 'Require Export %s.%s.\n' "$logical_namespace" "$child"
      done

    find "$source_directory" -mindepth 1 -maxdepth 1 -type d |
      LC_ALL=C sort |
      while IFS= read -r child_directory; do
        child=$(capitalize "$(basename "$child_directory")")
        printf 'Require Export %s.%s.\n' "$logical_namespace" "$child"
      done
  } >"$target"
done

snapshot_inputs >"$inputs_after"
if ! cmp -s "$inputs_before" "$inputs_after"; then
  printf 'Source or typed Dune inputs changed during translation; refusing to install generated output.\n' >&2
  diff -u "$inputs_before" "$inputs_after" >&2 || true
  exit 1
fi

rm -rf "$output"
mv "$staging" "$output"

# Paths are relative to [output], so this manifest is stable across checkouts.
(cd "$output" &&
  find . -type f -name '*.v' | LC_ALL=C sort |
  while IFS= read -r generated_file; do
    $hash_command "$generated_file"
  done) >"$output_hashes"

if [ -z "$keep_metadata" ]; then
  rm -rf "$metadata"
else
  printf 'Retained assumption metadata in %s\n' "$metadata"
fi
rm -f "$manifest" "$edges" "$order" "$inputs_before" "$inputs_after"
rm -rf "$metadata_input"
trap - EXIT HUP INT TERM

printf 'Generated %s Rocq source files in %s\n' \
  "$(find "$output" -type f -name '*.v' | wc -l | tr -d ' ')" \
  "$output"
printf 'Recorded generated source hashes in %s\n' "$output_hashes"
